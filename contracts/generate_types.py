"""Generate TypeScript declarations from the canonical schemas; use --check in CI."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
schema = json.loads((ROOT / "contracts/v1/schemas/domain.schema.json").read_text(encoding="utf-8"))


def ts(value):
    if "$ref" in value:
        return value["$ref"].split("/")[-1]
    if "const" in value:
        return json.dumps(value["const"])
    if "enum" in value:
        return " | ".join(json.dumps(v) for v in value["enum"])
    kind = value.get("type")
    if isinstance(kind, list):
        return " | ".join(ts({"type": item}) for item in kind)
    if kind == "array":
        return f"Array<{ts(value['items'])}>"
    if kind == "object":
        if isinstance(value.get("additionalProperties"), dict):
            return f"Record<string, {ts(value['additionalProperties'])}>"
        required = value.get("required", [])
        return (
            "{ "
            + "; ".join(
                f"{json.dumps(k)}{'' if k in required else '?'}: {ts(v)}"
                for k, v in value.get("properties", {}).items()
            )
            + " }"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


records = [name for name, value in schema["$defs"].items() if "id" in value.get("properties", {})]
output = "// Generated by contracts/generate_types.py. Edit the JSON Schema, then regenerate.\n"
for name, value in schema["$defs"].items():
    output += f"export type {name} = {ts(value)}\n"
output += (
    "export interface DomainTypes {\n" + "".join(f"  {name}: {name}\n" for name in records) + "}\n"
)
output += "export type RecordType = keyof DomainTypes\n"
path = ROOT / "frontend/src/lib/domain/types.generated.ts"
if "--check" in sys.argv:
    if not path.exists() or path.read_text(encoding="utf-8") != output:
        raise SystemExit("Domain types are stale; run contracts/generate_types.py")
    print("PASS: generated domain types match the canonical schemas")
else:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(output, encoding="utf-8")
    print(f"Generated {len(records)} record types")
